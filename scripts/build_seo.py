#!/usr/bin/env python3
"""Search-engine files for duhsketchcomedy.com, built from the site's own data.

Run from the repo root:  python3 scripts/build_seo.py
(The "Build SEO files" GitHub Action also runs it on every push and once a day.)

It writes:
  shows/<id>/index.html  one page per confirmed show in shows.json, with Google
                         Event data. Google only shows events from pages about a
                         single event, so each show needs its own page.
  sitemap.xml            homepage, show pages, and the blog once a post is live.
  index.html             only the block between the seo:start and seo:end
                         comments: the group's structured data (name, socials,
                         cast), read from the page itself.

Edit shows.json, posts/posts.json and index.html as usual. Never hand-edit the
generated files: the next run overwrites them.
"""
import datetime as dt
import html
import json
import re
import shutil
import sys
import unicodedata
from pathlib import Path
from zoneinfo import ZoneInfo

SITE = "https://duhsketchcomedy.com"
NAME = "DUH"
ALT_NAMES = ["duh", "DUH Sketch Comedy", "duh sketch comedy"]
NY = ZoneInfo("America/New_York")
MARK = "<!-- generated by scripts/build_seo.py: edit shows.json, not this file -->"
START = "<!-- seo:start"
END = "<!-- seo:end -->"

ROOT = Path(__file__).resolve().parent.parent
E = lambda s: html.escape(str(s or ""), quote=True)


def slugify(s):
    s = unicodedata.normalize("NFKD", str(s or "")).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def show_id(s):
    """Must match showId() in index.html."""
    if s.get("slug"):
        return slugify(s["slug"])
    return s["date"] + "-" + (slugify(s.get("venue") or s.get("title")) or "show")


def start_iso(s):
    """'2026-12-16' + '9:30 PM' -> '2026-12-16T21:30:00-05:00' (New York time)."""
    m = re.match(r"\s*(\d{1,2})(?::(\d{2}))?\s*([ap])\.?m\.?", s.get("time") or "", re.I)
    if not m:
        return s["date"]
    h, mi = int(m.group(1)) % 12, int(m.group(2) or 0)
    if m.group(3).lower() == "p":
        h += 12
    d = dt.date.fromisoformat(s["date"])
    return dt.datetime(d.year, d.month, d.day, h, mi, tzinfo=NY).isoformat()


def nice_date(iso, weekday=True):
    d = dt.date.fromisoformat(iso)
    fmt = f"%A, %B {d.day}, %Y" if weekday else f"%b {d.day}, %Y"
    return d.strftime(fmt)


def jsonld(obj):
    # "</" escaped so data can never close the script tag early.
    return json.dumps(obj, ensure_ascii=False, indent=2).replace("</", "<\\/")


def page_text(index_html):
    meta = re.search(r'<meta name="description" content="([^"]*)"', index_html)
    cast = re.findall(r'<li class="member">.*?<div class="name">([^<]+)</div>', index_html, re.S)
    socials = sorted(set(re.findall(r'href="(https://www\.(?:instagram|youtube|tiktok|facebook)\.com/[^"]+)"', index_html)))
    return (html.unescape(meta.group(1)) if meta else ""), [html.unescape(c).strip() for c in cast], socials


def group_block(index_html):
    desc, cast, socials = page_text(index_html)
    graph = [
        {"@type": "WebSite", "@id": SITE + "/#website", "url": SITE + "/", "name": NAME,
         "alternateName": ALT_NAMES, "publisher": {"@id": SITE + "/#duh"}},
        {"@type": "PerformingGroup", "@id": SITE + "/#duh", "name": NAME, "alternateName": ALT_NAMES,
         "url": SITE + "/", "logo": SITE + "/assets/icon-512.png", "image": SITE + "/assets/share.jpg",
         "description": desc, "genre": "Sketch comedy",
         "areaServed": {"@type": "City", "name": "New York City"},
         "location": {"@type": "Place", "address": {"@type": "PostalAddress", "addressLocality": "New York",
                                                    "addressRegion": "NY", "addressCountry": "US"}},
         "sameAs": socials,
         "member": [{"@type": "Person", "name": n} for n in cast]},
    ]
    return (START + " (generated by scripts/build_seo.py from this page: edit the page, not this block) -->\n"
            '<script type="application/ld+json">\n' + jsonld({"@context": "https://schema.org", "@graph": graph})
            + "\n</script>\n" + END)


def event_data(s, url):
    where = {"@type": "PostalAddress", "addressLocality": s.get("city") or "New York",
             "addressRegion": s.get("region") or "NY", "addressCountry": "US"}
    if s.get("address"):
        where["streetAddress"] = s["address"]
    if s.get("zip"):
        where["postalCode"] = str(s["zip"])
    ev = {"@context": "https://schema.org", "@type": "ComedyEvent", "@id": url + "#event",
          "name": s.get("title") or "DUH live", "url": url, "startDate": start_iso(s),
          "eventStatus": "https://schema.org/EventScheduled",
          "eventAttendanceMode": "https://schema.org/OfflineEventAttendanceMode",
          "location": {"@type": "Place", "name": s.get("venue") or "", "address": where},
          "image": [SITE + (s.get("image") or "/assets/share.jpg")],
          "description": s.get("blurb") or "Live sketch comedy from DUH in New York City.",
          "performer": {"@type": "PerformingGroup", "@id": SITE + "/#duh", "name": NAME, "url": SITE + "/"}}
    if s.get("tickets", "").startswith("https://"):
        offer = {"@type": "Offer", "url": s["tickets"], "availability": "https://schema.org/InStock"}
        if s.get("price") not in (None, ""):
            offer.update(price=str(s["price"]), priceCurrency="USD")
        ev["offers"] = offer
    org = s.get("organizer")
    if isinstance(org, dict) and org.get("name"):
        ev["organizer"] = {"@type": "Organization", "name": org["name"], **({"url": org["url"]} if org.get("url") else {})}
    return ev


