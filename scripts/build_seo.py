def live_posts():
    p = ROOT / "posts" / "posts.json"
    if not p.exists():
        return []
    today = dt.datetime.now(NY).date().isoformat()
    posts = json.loads(p.read_text()).get("posts") or []
    return [x for x in posts if x and x.get("slug") and x.get("title") and x.get("date")
            and not x.get("draft") and x["date"] <= today]


def main():
    shows = json.loads((ROOT / "shows.json").read_text()).get("shows") or []
    shows = [s for s in shows if s.get("confirmed") is not False
             and re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(s.get("date", "")))]
    shows.sort(key=lambda s: (s["date"], s.get("sort", "")))

    out = ROOT / "shows"
    out.mkdir(exist_ok=True)
    keep = set()
    for s in shows:
        sid = show_id(s)
        if sid in keep:
            sys.exit(f"Two shows share the page id {sid}. Give one a \"slug\" in shows.json.")
        keep.add(sid)
        (out / sid).mkdir(exist_ok=True)
        (out / sid / "index.html").write_text(show_page(s, sid))
    # Remove pages this script made for shows that are no longer in shows.json.
    for d in out.iterdir():
        f = d / "index.html"
        if d.is_dir() and d.name not in keep and f.exists() and MARK in f.read_text():
            shutil.rmtree(d)
    if not any(out.iterdir()):
        out.rmdir()

    urls = [SITE + "/"] + [f"{SITE}/shows/{show_id(s)}/" for s in shows]
    posts = live_posts()
    if posts:
        urls.append(SITE + "/blog/")
        urls += [f"{SITE}/blog/post.html?p={x['slug']}" for x in posts]
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{E(u)}</loc></url>\n" for u in urls)
        + "</urlset>\n")

    idx = ROOT / "index.html"
    page = idx.read_text()
    block = group_block(page)
    if START in page and END in page:
        page = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, page, count=1, flags=re.S)
    else:
        page = page.replace("</head>", block + "\n</head>", 1)
    idx.write_text(page)
    print(f"{len(shows)} show page(s), {len(urls)} sitemap URL(s), group data refreshed.")


if __name__ == "__main__":
    main()
